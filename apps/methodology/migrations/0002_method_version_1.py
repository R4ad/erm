def create_version_1(apps, schema_editor):
    MethodVersion = apps.get_model("methodology", "MethodVersion")
    Scale = apps.get_model("methodology", "Scale")
    ScaleLevel = apps.get_model("methodology", "ScaleLevel")
    LikelihoodCell = apps.get_model("methodology", "LikelihoodCell")
    RiskLevel = apps.get_model("methodology", "RiskLevel")
    ImpactFloor = apps.get_model("methodology", "ImpactFloor")
    BcRule = apps.get_model("methodology", "BcRule")
    MethodParameter = apps.get_model("methodology", "MethodParameter")

    now = timezone.now()
    version = MethodVersion.objects.create(
        number=1,
        title="روش v5",
        status="active",
        likelihood_strategy="paths_v5",
        impact_strategy="max",
        source=SOURCE,
        change_notes=CHANGE_NOTES,
        impact_guidance=IMPACT_GUIDANCE,
        decision_guidance=DECISION_GUIDANCE,
        acceptance_guidance=ACCEPTANCE_GUIDANCE,
        activated_at=now,
    )
    created = {"MethodVersion": [version], "Scale": [], "ScaleLevel": [], "LikelihoodCell": [], "RiskLevel": []}

    for order, data in enumerate(SCALES, start=1):
        fields = {key: value for key, value in data.items() if key != "levels"}
        scale = Scale.objects.create(version=version, order=order, **fields)
        created["Scale"].append(scale)
        for value, name, criteria, lower, upper in data["levels"]:
            level = ScaleLevel.objects.create(
                scale=scale,
                value=value,
                name=name,
                criteria=criteria,
                lower=decimal_or_none(lower),
                upper=decimal_or_none(upper),
            )
            created["ScaleLevel"].append(level)

    for a, row in enumerate(LIKELIHOOD_TABLE, start=1):
        for b, likelihood in enumerate(row, start=1):
            cell = LikelihoodCell.objects.create(version=version, a=a, b=b, likelihood=likelihood)
            created["LikelihoodCell"].append(cell)

    by_rank = {}
    for data in RISK_LEVELS:
        by_rank[data["rank"]] = RiskLevel.objects.create(version=version, **data)
    created["RiskLevel"] = list(by_rank.values())

    created["ImpactFloor"] = [
        ImpactFloor.objects.create(version=version, min_impact=impact, min_level=by_rank[rank])
        for impact, rank in IMPACT_FLOORS
    ]
    created["BcRule"] = [
        BcRule.objects.create(
            version=version, bc=bc, min_e=min_e, min_count=count, needs_independence=independent
        )
        for bc, min_e, count, independent in BC_RULES
    ]
    created["MethodParameter"] = [
        MethodParameter.objects.create(version=version, key=key, value=Decimal(value), note=note)
        for key, value, note in PARAMETERS
    ]

    for model_name, rows in created.items():
        add_initial_history(apps, model_name, rows, now)


def add_initial_history(apps, model_name, rows, now):
    """برای هر ردیف تازه یک ردیف «ایجاد» در تاریخچه می‌سازد تا اولین ویرایشش با چیزی مقایسه شود، مثل
    migration 0007 اپ accounts. در migration سیگنال‌های simple-history اجرا نمی‌شوند."""
    historical = apps.get_model("methodology", f"Historical{model_name}")
    copied = [
        field.attname
        for field in historical._meta.fields
        if not field.name.startswith("history_") and field.name != "id"
    ]
    historical.objects.bulk_create(
        historical(
            id=row.pk,
            history_date=now,
            history_type="+",
            history_change_reason=HISTORY_REASON,
            **{name: getattr(row, name) for name in copied},
        )
        for row in rows
    )


